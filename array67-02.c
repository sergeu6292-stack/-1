/*Для данного целого x найти значение следующей функции f, принимающей значения целого типа:
f (x) = 2·x, если x < −2 или x > 2−3·x, в противном случае. Выполнил: Мартиросян Сергей */

#include <stdio.h>
int main () {
	int x;
	scanf ("%d", &x);
	if (x < -2 || x > 2) {
		 x = 2 * x;
		printf ("%d", x);
	}
	else {
		 x = -3 * x;
		printf("%d", x);
	}
	
	return 0;
}
